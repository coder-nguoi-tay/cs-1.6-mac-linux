#define ART_BANNER		"gfx/shell/head_creategame"
#define CREATEGAME_CFGFILE	"creategame.cfg"	// persisted New Game settings (bots/difficulty/roundtime/money)
#define CREATEGAME_MAPCFG	"creategame_map.cfg"	// exec'd by engine at every server spawn (mapchangecfgfile)

// New Game extra settings, persisted in CREATEGAME_CFGFILE and applied through CREATEGAME_MAPCFG
// (yb_* and mp_* cvars only exist after the game dll spawns, so engine cvars cannot be linked here)
static struct creategame_t
{
	int bots;	// yb_quota 0..20
	int diff;	// spin index 0..3 -> yb_difficulty 1..4
	int round;	// mp_roundtime minutes 1..9
	int money;	// mp_startmoney 800..16000
	void Defaults( void )
	{
		bots = 9;
		diff = 1;	// Normal
		round = 5;
		money = 800;
	}
} g_createCfg;

static const char *g_szDifficultyLabels[] = { "Easy", "Normal", "Hard", "Expert" };

// Load persisted create-game settings from gamedir
static void CGame_LoadSettings( void )
{
	g_createCfg.Defaults();

	int len = 0;
	char *buf = (char *)EngFuncs::COM_LoadFile( CREATEGAME_CFGFILE, &len );
	if( !buf )
		return;

	char key[64], val[64];
	char *pos = buf;

	while( pos < buf + len )
	{
		int k = 0;
		while( pos < buf + len && *pos == ' ' ) pos++;
		while( pos < buf + len && *pos != ' ' && *pos != '\n' && k < (int)sizeof( key ) - 1 )
			key[k++] = *pos++;
		key[k] = 0;
		while( pos < buf + len && *pos == ' ' ) pos++;
		int v = 0;
		while( pos < buf + len && *pos != '\n' && v < (int)sizeof( val ) - 1 )
			val[v++] = *pos++;
		val[v] = 0;
		while( pos < buf + len && *pos != '\n' ) pos++;
		if( pos < buf + len ) pos++;

		if( !key[0] || !val[0] )
			continue;

		if( !strcmp( key, "bots" ))          g_createCfg.bots  = bound( 0, atoi( val ), 20 );
		else if( !strcmp( key, "difficulty" )) g_createCfg.diff = bound( 0, atoi( val ) - 1, 3 );
		else if( !strcmp( key, "roundtime" ))  g_createCfg.round = bound( 1, atoi( val ), 9 );
		else if( !strcmp( key, "startmoney" )) g_createCfg.money = bound( 800, atoi( val ), 16000 );
	}

	EngFuncs::COM_FreeFile( buf );
}

// Save settings and prepare map-change config applied by engine at server spawn
static void CGame_SaveSettings( void )
{
	char text[256];
	int len = snprintf( text, sizeof( text ),
		"// generated by New Game dialog\n"
		"bots %d\ndifficulty %d\nroundtime %d\nstartmoney %d\n",
		g_createCfg.bots, g_createCfg.diff + 1, g_createCfg.round, g_createCfg.money );

	EngFuncs::COM_SaveFile( CREATEGAME_CFGFILE, text, len );

	// applied by engine on every map spawn, when game dll cvars exist
	len = snprintf( text, sizeof( text ),
		"yb_quota \"%d\"\n"
		"yb_difficulty \"%d\"\n"
		"mp_roundtime \"%d\"\n"
		"mp_startmoney \"%d\"\n",
		g_createCfg.bots, g_createCfg.diff + 1, g_createCfg.round, g_createCfg.money );

	EngFuncs::COM_SaveFile( CREATEGAME_MAPCFG, text, len );
	EngFuncs::CvarSetString( "mapchangecfgfile", CREATEGAME_MAPCFG );
}

static const char *MAX_CLIENTS_STRING()
{
	static CUtlString maxClientsStr;
	maxClientsStr.Format( "%d", MAX_CLIENTS );
	return maxClientsStr.String();
}

